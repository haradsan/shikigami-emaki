// プレイヤー(CPU)のキャラ定義を取得（charKey はステージid）
function charOf(p) {
  return (p && p.charKey && CHARACTERS[p.charKey]) || null;
}

// キャラの顔絵（円形メダリオンのSVG）。id を使わないので何個並べても安全
